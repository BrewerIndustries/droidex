// chart, and erikpeik/droidex's droidStats.json.
//
// sell is a flat 70% of cost game-wide, so it is derived rather than stored.
//
// Fusion-exclusive droids (v1.27) carry income only. They cannot be bought, so
// there is no cost to derive a sell value from, and the sheet's own value column
// for them is still being filled in — 16 of the 17 deviate from the standard
// tier progression, with figures as implausible as 14,500x base at Stellar. Left
// out rather than imported wrong.
// Iconics are bought with Nova Crystals and earn a share of total income, so they
// carry costNote/incomeNote instead of numbers.

